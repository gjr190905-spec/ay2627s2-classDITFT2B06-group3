SET client_min_messages = warning;
SET search_path TO public;   -- always create in "public", where the app looks

-- ---------------------------------------------------------------------
-- Vendor: one row per stall
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "Vendor" (
    "id"               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "stallName"        TEXT        NOT NULL,
    "logoUrl"          TEXT,                                  -- one profile picture per vendor
    "isOpen"           BOOLEAN     NOT NULL DEFAULT FALSE,
    "statusUpdatedAt"  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "createdAt"        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- same limits the app checks (2–40 characters)
    CONSTRAINT "Vendor_stallName_length"
        CHECK (char_length(btrim("stallName")) BETWEEN 2 AND 40)
);

-- Shop names are unique, ignoring upper/lower case and outer spaces
-- (same index name as vendor_profile_migration.sql, so that file can still be run safely)
CREATE UNIQUE INDEX IF NOT EXISTS "Vendor_stallName_unique"
    ON "Vendor" (lower(btrim("stallName")));

-- ---------------------------------------------------------------------
-- StoreClosure: a record each time a vendor closes their stall, with the reason
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "StoreClosure" (
    "id"           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "vendorId"     INTEGER     NOT NULL REFERENCES "Vendor"("id") ON DELETE CASCADE,
    "reason"       TEXT        NOT NULL,
    "otherReason"  VARCHAR(255),
    "closedAt"     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- codes must match CLOSURE_REASONS in Vendor.model.js
    CONSTRAINT "StoreClosure_reason_check"
        CHECK ("reason" IN ('SOLD_OUT', 'BREAK', 'END_OF_DAY', 'EQUIPMENT', 'STAFF', 'OTHER')),
    -- "Other" needs typed text; every other reason has none
    CONSTRAINT "StoreClosure_otherReason_check"
        CHECK (("reason" = 'OTHER') = ("otherReason" IS NOT NULL AND btrim("otherReason") <> ''))
);

CREATE INDEX IF NOT EXISTS "StoreClosure_vendorId_idx" ON "StoreClosure" ("vendorId", "closedAt");

-- Check: should list both tables
SELECT table_name FROM information_schema.tables
 WHERE table_schema = current_schema() AND table_name IN ('Vendor', 'StoreClosure');
